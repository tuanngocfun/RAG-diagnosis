@dataclass
class CaseTextBuildResult:
    text: str
    sections: List[str]
    estimated_tokens: int


def parse_maybe_list(value: Any) -> List[str]:
    if value is None:
        return []
    if isinstance(value, list):
        return [str(v).strip() for v in value if str(v).strip()]
    text = str(value).strip()
    if not text:
        return []
    try:
        parsed = json.loads(text)
    except json.JSONDecodeError:
        return [text]
    if isinstance(parsed, list):
        return [str(v).strip() for v in parsed if str(v).strip()]
    if parsed is None:
        return []
    return [str(parsed).strip()]


def is_empty_value(value: Any) -> bool:
    return value in (None, "", [], {})


def merge_non_empty_fields(preferred: Dict[str, Any], fallback: Dict[str, Any]) -> Dict[str, Any]:
    """Merge two records preferring non-empty values from preferred."""
    merged = dict(fallback or {})
    for key, value in (preferred or {}).items():
        if not is_empty_value(value):
            merged[key] = value
    return merged


def read_jsonl(path: Path) -> List[Dict]:
    rows: List[Dict] = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            rows.append(json.loads(line))
    return rows


def write_jsonl(path: Path, rows: Iterable[Dict]) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with open(path, "w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            count += 1
    return count


def read_case_ids(path: Path) -> List[str]:
    ordered: List[str] = []
    seen = set()
    with open(path, "r", encoding="utf-8") as f:
        for raw in f:
            cid = raw.strip()
            if not cid:
                continue
            cid = cid.upper()
            if not CASE_ID_RE.match(cid):
                raise ValueError(f"Invalid case_id in list: {cid}")
            if cid not in seen:
                seen.add(cid)
                ordered.append(cid)
    return ordered


def parse_tagged(xml_like_text: str, tag_name: str) -> str:
    if not xml_like_text:
        return ""
    pattern = rf"<{re.escape(tag_name)}>(.*?)</{re.escape(tag_name)}>"
    match = re.search(pattern, xml_like_text, flags=re.IGNORECASE | re.DOTALL)
    return match.group(1).strip() if match else ""


def normalize_dx_name(value: str) -> str:
    text = (value or "").strip()
    if not text:
        return "Non-Leishmaniasis"
    if text.upper() == "NO_MATCH":
        return "Non-Leishmaniasis"
    return text


def build_diag_name(case_record: Dict) -> str:
    candidates = [
        case_record.get("primary_disease_mapped", ""),
        case_record.get("primary_diagnosis_text", ""),
        case_record.get("prompt1_final_diagnosis_mapped", ""),
        case_record.get("prompt1_final_diagnosis", ""),
    ]
    matched = case_record.get("matched_disease_candidates") or []
    if matched:
        candidates.append(str(matched[0]))

    for candidate in candidates:
        normalized = normalize_dx_name(str(candidate))
        if normalized and normalized != "Non-Leishmaniasis":
            return normalized

    for candidate in candidates:
        normalized = normalize_dx_name(str(candidate))
        if normalized:
            return normalized

    return "Non-Leishmaniasis"


def _normalize_text_block(value: Any) -> str:
    text = str(value or "").strip()
    if not text or text.lower() == "nan":
        return ""
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def _normalize_sentence_spacing(text: str) -> str:
    return re.sub(r"\s+", " ", (text or "").strip())


def _split_sentences(text: str) -> List[str]:
    normalized = _normalize_text_block(text)
    if not normalized:
        return []
    return [part.strip() for part in re.split(r"(?<=[.!?])\s+", normalized) if part.strip()]


def _trim_words_to_tokens(text: str, max_tokens: int) -> str:
    normalized = _normalize_text_block(text)
    if not normalized or max_tokens <= 0:
        return ""
    max_words = max(1, int(max_tokens / 1.3))
    return " ".join(normalized.split()[:max_words]).strip()


def _trim_to_sentence_budget(text: str, max_tokens: int) -> str:
    normalized = _normalize_text_block(text)
    if not normalized or max_tokens <= 0:
        return ""
    if estimate_tokens(normalized) <= max_tokens:
        return normalized

    selected: List[str] = []
    for sentence in _split_sentences(normalized):
        candidate = " ".join(selected + [sentence]).strip()
        if selected and estimate_tokens(candidate) > max_tokens:
            break
        if not selected and estimate_tokens(sentence) > max_tokens:
            return _trim_words_to_tokens(sentence, max_tokens)
        selected.append(sentence)

    if selected:
        return " ".join(selected).strip()
    return _trim_words_to_tokens(normalized, max_tokens)


def _dedupe_section_texts(values: Iterable[str]) -> List[str]:
    unique_values: List[str] = []
    seen = set()
    for value in values:
        normalized = _normalize_sentence_spacing(value).lower()
        if not normalized or normalized in seen:
            continue
        seen.add(normalized)
        unique_values.append(_normalize_text_block(value))
    return unique_values


def _render_section(label: str, body: str) -> str:
    body = _normalize_text_block(body)
    if not body:
        return ""
    return f"{label}:\n{body}"


def _extract_prompt_fallback(case_record: Dict) -> str:
    prompt2_quality_pass = bool(case_record.get("prompt2_quality_pass", False))
    values = [
        case_record.get("prompt2_case_prompt", "") if prompt2_quality_pass else "",
        case_record.get("prompt1_case_prompt", ""),
        parse_tagged(case_record.get("prompt1_response_raw", ""), "case_prompt"),
    ]
    for value in values:
        text = _normalize_text_block(value)
        if text:
            return text
    return ""


def _build_reference_diagnosis(case_record: Dict) -> str:
    diagnosis = build_diag_name(case_record)
    diagnosis_type = str(case_record.get("diagnosis_type") or "Non-Leishmaniasis").strip() or "Non-Leishmaniasis"
    reference = [f"Diagnosis: {diagnosis}.", f"Diagnosis Type: {diagnosis_type}."]
    species = _normalize_text_block(case_record.get("species"))
    if species:
        reference.append(f"Species: {species}.")
    return " ".join(reference)


def _compose_case_sections(case_record: Dict, source_case: Dict) -> List[Tuple[str, str]]:
    source_narrative = _normalize_text_block(source_case.get("case_text"))
    source_abstract = _normalize_text_block(source_case.get("abstract"))
    structured_case_text = _normalize_text_block(case_record.get("case_text"))
    structured_abstract = _normalize_text_block(case_record.get("abstract"))
    evidence = _normalize_text_block(case_record.get("evidence"))
    rationale = _normalize_text_block(case_record.get("rationale"))
    fallback_prompt = _extract_prompt_fallback(case_record)

    narrative_parts: List[str] = []
    if source_narrative:
        narrative_parts.append(source_narrative)
    elif structured_case_text:
        narrative_parts.append(structured_case_text)
    if source_abstract and (
        not narrative_parts or estimate_tokens("\n\n".join(narrative_parts)) < NARRATIVE_MIN_COMPLETE_TOKENS
    ):
        narrative_parts.append(source_abstract)
    elif structured_abstract and (
        not narrative_parts or estimate_tokens("\n\n".join(narrative_parts)) < NARRATIVE_MIN_COMPLETE_TOKENS
    ):
        narrative_parts.append(structured_abstract)

    narrative = "\n\n".join(_dedupe_section_texts(narrative_parts))
    if not narrative and fallback_prompt:
        narrative = fallback_prompt

    sections: List[Tuple[str, str]] = []
    if narrative:
        sections.append(("Clinical Narrative", narrative))
    if evidence:
        sections.append(("Key Diagnostic Evidence", evidence))
    if rationale:
        sections.append(("Reasoning Summary", rationale))

    reference_diagnosis = _build_reference_diagnosis(case_record)
    if reference_diagnosis:
        sections.append(("Reference Diagnosis", reference_diagnosis))
    return sections


def _trim_case_sections(sections: List[Tuple[str, str]], max_tokens: int = CASE_TEXT_MAX_TOKENS) -> CaseTextBuildResult:
    lookup = {label: _normalize_text_block(body) for label, body in sections if _normalize_text_block(body)}
    narrative = lookup.get("Clinical Narrative", "")
    evidence = lookup.get("Key Diagnostic Evidence", "")
    reasoning = lookup.get("Reasoning Summary", "")
    reference = lookup.get("Reference Diagnosis", "")

    mandatory_sections: List[Tuple[str, str]] = []
    if evidence:
        mandatory_sections.append(("Key Diagnostic Evidence", evidence))
    if reference:
        mandatory_sections.append(("Reference Diagnosis", reference))

    mandatory_text = "\n\n".join(_render_section(label, body) for label, body in mandatory_sections if body)
    mandatory_tokens = estimate_tokens(mandatory_text) if mandatory_text else 0

    if mandatory_tokens > max_tokens:
        reference_tokens = estimate_tokens(_render_section("Reference Diagnosis", reference)) if reference else 0
        evidence_budget = max(max_tokens - reference_tokens - 8, 0)
        trimmed_evidence = _trim_to_sentence_budget(evidence, evidence_budget)
        mandatory_sections = []
        if trimmed_evidence:
            mandatory_sections.append(("Key Diagnostic Evidence", trimmed_evidence))
        if reference:
            mandatory_sections.append(("Reference Diagnosis", reference))
        mandatory_text = "\n\n".join(_render_section(label, body) for label, body in mandatory_sections if body)
        mandatory_tokens = estimate_tokens(mandatory_text) if mandatory_text else 0

    remaining_budget = max(max_tokens - mandatory_tokens, 0)
    trimmed_narrative = ""
    trimmed_reasoning = ""
    if narrative and remaining_budget > 0:
        narrative_budget = remaining_budget
        if reasoning:
            reasoning_reserve = min(max(estimate_tokens(reasoning), 40), max(remaining_budget // 3, 40))
            narrative_budget = max(remaining_budget - reasoning_reserve, remaining_budget // 2)
        trimmed_narrative = _trim_to_sentence_budget(narrative, narrative_budget)
        remaining_budget = max(remaining_budget - estimate_tokens(trimmed_narrative), 0)
    if reasoning and remaining_budget > 0:
        trimmed_reasoning = _trim_to_sentence_budget(reasoning, remaining_budget)

    selected_sections: List[Tuple[str, str]] = []
    for label, body in [
        ("Clinical Narrative", trimmed_narrative),
        ("Key Diagnostic Evidence", dict(mandatory_sections).get("Key Diagnostic Evidence", "")),
        ("Reasoning Summary", trimmed_reasoning),
        ("Reference Diagnosis", dict(mandatory_sections).get("Reference Diagnosis", "")),
    ]:
        body = _normalize_text_block(body)
        if body:
            selected_sections.append((label, body))

    rendered = "\n\n".join(
        _render_section(label, body)
        for label, body in selected_sections
        if _render_section(label, body)
    ).strip()

    if estimate_tokens(rendered) > max_tokens:
        overflow = estimate_tokens(rendered) - max_tokens
        if trimmed_reasoning:
            reasoning_budget = max(estimate_tokens(trimmed_reasoning) - overflow - 4, 0)
            trimmed_reasoning = _trim_to_sentence_budget(trimmed_reasoning, reasoning_budget)
        selected_sections = []
        for label, body in [
            ("Clinical Narrative", trimmed_narrative),
            ("Key Diagnostic Evidence", dict(mandatory_sections).get("Key Diagnostic Evidence", "")),
            ("Reasoning Summary", trimmed_reasoning),
            ("Reference Diagnosis", dict(mandatory_sections).get("Reference Diagnosis", "")),
        ]:
            body = _normalize_text_block(body)
            if body:
                selected_sections.append((label, body))
        rendered = "\n\n".join(
            _render_section(label, body)
            for label, body in selected_sections
            if _render_section(label, body)
        ).strip()

    if estimate_tokens(rendered) > max_tokens and trimmed_narrative:
        overflow = estimate_tokens(rendered) - max_tokens
        narrative_budget = max(estimate_tokens(trimmed_narrative) - overflow - 4, 0)
        trimmed_narrative = _trim_to_sentence_budget(trimmed_narrative, narrative_budget)
        selected_sections = []
        for label, body in [
            ("Clinical Narrative", trimmed_narrative),
            ("Key Diagnostic Evidence", dict(mandatory_sections).get("Key Diagnostic Evidence", "")),
            ("Reasoning Summary", trimmed_reasoning),
            ("Reference Diagnosis", dict(mandatory_sections).get("Reference Diagnosis", "")),
        ]:
            body = _normalize_text_block(body)
            if body:
                selected_sections.append((label, body))
        rendered = "\n\n".join(
            _render_section(label, body)
            for label, body in selected_sections
            if _render_section(label, body)
        ).strip()

    max_words_for_two_chunks = int(
        (FIXED_CHUNK_MAX_TOKENS / 1.3) + ((FIXED_CHUNK_MAX_TOKENS - FIXED_CHUNK_OVERLAP_TOKENS) / 1.3)
    )
    words = rendered.split()
    if len(words) > max_words_for_two_chunks:
        safe_word_budget = max_words_for_two_chunks
        trimmed_narrative = _trim_words_to_tokens(trimmed_narrative, max(int(safe_word_budget * 1.3), 0))
        selected_sections = []
        for label, body in [
            ("Clinical Narrative", trimmed_narrative),
            ("Key Diagnostic Evidence", dict(mandatory_sections).get("Key Diagnostic Evidence", "")),
            ("Reasoning Summary", trimmed_reasoning),
            ("Reference Diagnosis", dict(mandatory_sections).get("Reference Diagnosis", "")),
        ]:
            body = _normalize_text_block(body)
            if body:
                selected_sections.append((label, body))
        rendered = "\n\n".join(
            _render_section(label, body)
            for label, body in selected_sections
            if _render_section(label, body)
        ).strip()

    return CaseTextBuildResult(
        text=rendered,
        sections=[label for label, _ in selected_sections],
        estimated_tokens=estimate_tokens(rendered),
    )


def build_case_text(case_record: Dict, source_case: Dict) -> CaseTextBuildResult:
    return _trim_case_sections(_compose_case_sections(case_record, source_case))


def load_source_candidates(path: Path) -> Dict[str, Dict]:
    if not path.exists():
        raise FileNotFoundError(f"Source candidates JSONL not found: {path}")

    rows_by_case: Dict[str, Dict] = {}
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            case_id = str(row.get("case_id", "")).upper()
            if case_id:
                rows_by_case[case_id] = row
    return rows_by_case


