def load_case_record(case_records_dir: Path, case_id: str) -> Tuple[Path, Dict]:
    path = case_records_dir / f"{case_id}.json"
    if not path.exists():
        raise FileNotFoundError(str(path))
    with open(path, "r", encoding="utf-8") as f:
        row = json.load(f)
    if str(row.get("case_id", "")).upper() != case_id:
        raise ValueError(f"Case ID mismatch in {path}: expected {case_id}, got {row.get('case_id')}")
    return path, row


def main() -> None:
    parser = argparse.ArgumentParser(description="Build non-leish train variants from selected case IDs")
    parser.add_argument("--phase-name", required=True, help="Name suffix for output artifacts, e.g. phase1a_tierA")
    parser.add_argument("--case-list", required=True, type=Path, help="Text file with one case_id per line")
    parser.add_argument(
        "--case-records-dir",
        type=Path,
        default=Path(
            "/home/ngocnt/Leishmania_v3/data/Infectious_disease_v2/"
            "classified_medgemma_27b_multimodal_fresh1_recovered_prompt12_stage_backfill_unified6208/case_records"
        ),
    )
    parser.add_argument(
        "--split-dir",
        type=Path,
        default=Path("/home/ngocnt/experiments/structured_cases_v4/leishmaniasis_verified_v2"),
    )
    parser.add_argument(
        "--source-candidates-jsonl",
        type=Path,
        default=Path("/home/ngocnt/Leishmania_v3/data/Infectious_disease_v2/infectious_candidates_cases.jsonl"),
        help="Source JSONL with case_image_files/case_image_captions fields",
    )
    parser.add_argument(
        "--classified-cases-jsonl",
        type=Path,
        default=Path(
            "/home/ngocnt/Leishmania_v3/data/Infectious_disease_v2/"
            "classified_medgemma_27b_multimodal_fresh1_recovered_prompt12_stage_backfill_unified6208/classified_cases.jsonl"
        ),
        help="Source JSONL for structured case text and pseudolabel mappings",
    )
    parser.add_argument(
        "--image-inventory-csv",
        type=Path,
        default=Path("/home/ngocnt/Leishmania_v3/data/Infectious_disease_v2/aligned_case_images/image_inventory.csv"),
        help="Aligned image inventory CSV",
    )
    parser.add_argument(
        "--aligned-images-root",
        type=Path,
        default=Path("/home/ngocnt/Leishmania_v3/data/Infectious_disease_v2/aligned_case_images"),
        help="Root folder with aligned case images",
    )
    parser.add_argument(
        "--images-target-root",
        type=Path,
        default=Path("/home/ngocnt/Leishmania_v3/data/leishmaniasis_multimodal/images"),
        help="Target root for train image files expected by indexer",
    )
    parser.add_argument(
        "--materialize-images",
        action="store_true",
        help="Copy/symlink linked images into images-target-root and populate query_image_paths",
    )
    parser.add_argument("--fail-on-missing", action="store_true", help="Stop if any case record is missing")
    args = parser.parse_args()

    split_dir = args.split_dir
    base_train_raw = split_dir / "train.jsonl"
    base_train_normalized = split_dir / "train_pseudolabel_v2_normalized.jsonl"
    test_raw = split_dir / "test.jsonl"
    test_normalized = split_dir / "test_pseudolabel_v2_normalized.jsonl"

    output_dir = split_dir / "nonleish_additions" / "generated"
    output_dir.mkdir(parents=True, exist_ok=True)

    requested_ids = read_case_ids(args.case_list)
    source_candidates = load_source_candidates(args.source_candidates_jsonl)
    classified_cases = load_classified_cases(args.classified_cases_jsonl)
    inventory_by_case_id, inventory_by_article_id = load_image_inventory(args.image_inventory_csv)

    train_raw_rows = read_jsonl(base_train_raw)
    train_norm_rows = read_jsonl(base_train_normalized)
    test_raw_rows = read_jsonl(test_raw)
    test_norm_rows = read_jsonl(test_normalized)

    train_ids = {str(r.get("case_id", "")).upper() for r in train_raw_rows} | {
        str(r.get("case_id", "")).upper() for r in train_norm_rows
    }
    test_ids = {str(r.get("case_id", "")).upper() for r in test_raw_rows} | {
        str(r.get("case_id", "")).upper() for r in test_norm_rows
    }

    missing_ids: List[str] = []
    collision_train_ids: List[str] = []
    collision_test_ids: List[str] = []
    added_rows_raw: List[Dict] = []
    added_rows_norm: List[Dict] = []
    image_audit: Dict[str, Dict[str, Any]] = {}

    for case_id in requested_ids:
        if case_id in train_ids:
            collision_train_ids.append(case_id)
            continue
        if case_id in test_ids:
            collision_test_ids.append(case_id)
            continue

        try:
            source_path, case_record = load_case_record(args.case_records_dir, case_id)
        except FileNotFoundError:
            if case_id in classified_cases:
                source_path = args.classified_cases_jsonl
                case_record = classified_cases[case_id]
            else:
                missing_ids.append(case_id)
                if args.fail_on_missing:
                    raise
                continue

        case_record = merge_non_empty_fields(classified_cases.get(case_id, {}), case_record)

        source_case = source_candidates.get(case_id, {})
        article_id = str(case_record.get("article_id") or case_id.rsplit("_", 1)[0]).upper()
        source_image_metadata = extract_source_image_metadata(source_case)
        images, query_image_paths, audit = build_images_from_source(
            case_id=case_id,
            article_id=article_id,
            source_case=source_case,
            inventory_by_case_id=inventory_by_case_id,
            inventory_by_article_id=inventory_by_article_id,
            aligned_images_root=args.aligned_images_root,
            materialize_images=args.materialize_images,
            images_target_root=args.images_target_root,
        )
        image_audit[case_id] = audit
        case_text_result = build_case_text(case_record, source_case)

        added_rows_raw.append(
            to_raw_train_row(case_record, source_path, case_text_result, images, source_image_metadata)
        )
        added_rows_norm.append(
            to_normalized_row(
                case_record,
                source_path,
                args.phase_name,
                case_text_result,
                images,
                query_image_paths,
                audit,
                source_image_metadata,
            )
        )

    merged_raw = train_raw_rows + added_rows_raw
    merged_norm = train_norm_rows + added_rows_norm

    base_norm_by_case_id = {str(row.get("case_id", "")).upper(): row for row in train_norm_rows}
    merged_norm_by_case_id = {str(row.get("case_id", "")).upper(): row for row in merged_norm}
    missing_existing_case_ids = sorted(set(base_norm_by_case_id) - set(merged_norm_by_case_id))
    changed_existing_case_ids = sorted(
        case_id
        for case_id, row in base_norm_by_case_id.items()
        if case_id in merged_norm_by_case_id and merged_norm_by_case_id[case_id] != row
    )

    raw_out = output_dir / f"train_{args.phase_name}.jsonl"
    norm_out = output_dir / f"train_pseudolabel_v2_{args.phase_name}.jsonl"
    manifest_out = output_dir / f"merge_manifest_{args.phase_name}.json"
    validation_out = output_dir / f"merge_validation_{args.phase_name}.json"

    write_jsonl(raw_out, merged_raw)
    write_jsonl(norm_out, merged_norm)

    stats = MergeStats(
        phase_name=args.phase_name,
        requested_case_count=len(requested_ids),
        unique_requested_case_count=len(requested_ids),
        added_case_count=len(added_rows_raw),
        missing_case_count=len(missing_ids),
        collision_train_count=len(collision_train_ids),
        collision_test_count=len(collision_test_ids),
    )

    manifest = {
        "phase_name": args.phase_name,
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "case_list_file": str(args.case_list),
        "case_records_dir": str(args.case_records_dir),
        "classified_cases_jsonl": str(args.classified_cases_jsonl),
        "selected_case_ids": requested_ids,
        "added_case_ids": [row["case_id"] for row in added_rows_raw],
        "image_audit_by_case": image_audit,
        "missing_case_ids": missing_ids,
        "collision_train_case_ids": collision_train_ids,
        "collision_test_case_ids": collision_test_ids,
        "outputs": {
            "train_raw": str(raw_out),
            "train_pseudolabel_v2": str(norm_out),
        },
    }

    validation = {
        "stats": stats.__dict__,
        "base_counts": {
            "train_raw": len(train_raw_rows),
            "train_pseudolabel_v2": len(train_norm_rows),
            "test_raw": len(test_raw_rows),
            "test_pseudolabel_v2": len(test_norm_rows),
        },
        "result_counts": {
            "train_raw": len(merged_raw),
            "train_pseudolabel_v2": len(merged_norm),
        },
        "consistency": {
            "added_raw_equals_added_norm": len(added_rows_raw) == len(added_rows_norm),
            "all_added_non_leish": all(not row["is_leishmaniasis"] for row in added_rows_raw),
            "all_added_case_ids_unique": len({row["case_id"] for row in added_rows_raw}) == len(added_rows_raw),
            "added_with_images": sum(1 for row in added_rows_norm if row.get("images")),
            "added_with_query_image_paths": sum(1 for row in added_rows_norm if row.get("query_image_paths")),
            "baseline_rows_preserved": len(missing_existing_case_ids) == 0 and len(changed_existing_case_ids) == 0,
            "baseline_missing_case_count": len(missing_existing_case_ids),
            "baseline_changed_case_count": len(changed_existing_case_ids),
        },
        "baseline_preservation": {
            "missing_case_ids": missing_existing_case_ids,
            "changed_case_ids": changed_existing_case_ids,
        },
    }

    with open(manifest_out, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    with open(validation_out, "w", encoding="utf-8") as f:
        json.dump(validation, f, indent=2)

    print("=== Non-Leish Train Variant Build ===")
    print(f"phase_name={args.phase_name}")
    print(f"requested={len(requested_ids)}")
    print(f"added={len(added_rows_raw)}")
    print(f"missing={len(missing_ids)}")
    print(f"collision_train={len(collision_train_ids)}")
    print(f"collision_test={len(collision_test_ids)}")
    print(f"added_with_images={sum(1 for row in added_rows_norm if row.get('images'))}")
    print(f"materialize_images={bool(args.materialize_images)}")
    print(f"output_train_raw={raw_out}")
    print(f"output_train_pseudolabel_v2={norm_out}")
    print(f"validation={validation_out}")


if __name__ == "__main__":
    main()
